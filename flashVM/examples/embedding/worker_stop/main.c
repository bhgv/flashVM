#include "flashvm/worker.h"
/* Подключаем объявления используемых типов и функций. */
#include "../../example_support.h"

/* Define WorkerData struct and its representation. */
/* Объявляем тип, используемый в этом примере. */
typedef struct WorkerData
/* Начинаем блок инструкций или описание объекта. */
{
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Worker *handle;
    /* Завершаем выражение с указанным значением или аргументами. */
} WorkerData;

/* Compute and return callback. */
/* Определяем функцию callback; параметры передаются вызывающей стороной в указанном порядке. */
static FVM_Result callback(FVM_Context *ctx, const FVM_Value *input, FVM_Value *result,
                           /* Продолжаем объявление или выражение с указанными параметрами. */
                           void *userdata)
/* Начинаем блок инструкций или описание объекта. */
{

    /* Initialization / Инициализация локального состояния. */
    /* Сохраняем вычисленное значение: WorkerData *data. */
    WorkerData *data = (WorkerData *)userdata;
    /* Сохраняем вычисленное значение: int stop. */
    int stop = 0;

    /* Computation / Вычисление и обновление состояния. */
    /* Завершаем выражение с указанным значением или аргументами. */
    (void)ctx;
    /* Вызываем fvm_worker_stop_requested: проверяем запрос добровольного завершения.
     * data->handle — дескриптор рабочего потока.
     * &stop — адрес для признака запроса добровольного завершения.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_stop_requested(data->handle, &stop) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_stop_requested(data->handle, &stop) == FVM_OK", __FILE__,
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Записываем числовое значение и соответствующий тег типа. */
    fvm_value_number(result, input->number + (stop ? 1 : 0));
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return FVM_OK;
    /* Завершаем текущий блок или описание объекта. */
}

/* Initialize the example, run its API operations and release owned resources. */
/* Точка входа: запускаем последовательность действий этого примера. */
int main(void)
/* Начинаем блок инструкций или описание объекта. */
{

    /* Initialization / Инициализация локального состояния. */
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Config cfg;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Worker *workers[2];
    /* Завершаем выражение с указанным значением или аргументами. */
    WorkerData data[2];
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Value input, outputs[2];
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    unsigned int i;
    /* Вызываем fvm_config_init: заполняем настройки VM значениями по умолчанию.
     * &cfg — настройки VM.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_config_init(&cfg) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_config_init(&cfg) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Записываем числовое значение и соответствующий тег типа. */
    fvm_value_number(&input, 41);
    /* Организуем повторение операций до выполнения условия завершения. */
    for (i = 0; i < 2; ++i)
    /* Начинаем блок инструкций или описание объекта. */
    {
        /* Сохраняем вычисленное значение: data[i].handle. */
        data[i].handle = 0;
        /* Вызываем fvm_worker_run_suspended: создаём поток, ожидающий явного запуска.
         * &cfg — настройки создаваемой VM.
         * callback — callback рабочего потока.
         * &input — начальное значение callback.
         * &data[i] — данные хоста, живущие до join.
         * &workers[i] — адрес для потока, который сначала ожидает start.
         * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
        if (!(fvm_worker_run_suspended(&cfg, callback, &input, &data[i], &workers[i]) == FVM_OK))
        /* Начинаем обработку неуспешного вызова или неверного результата. */
        {
            /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
            fvm_example_fail(
                /* Продолжаем условие проверки или аргументы диагностического сообщения. */
                "fvm_worker_run_suspended(&cfg, callback, &input, &data[i], &workers[i]) == FVM_OK",
                /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                __FILE__, __LINE__);
            /* Завершаем ветку ошибки. */
        }
        /* Сохраняем вычисленное значение: data[i].handle. */
        data[i].handle = workers[i];
        /* Вызываем fvm_worker_stop: запрашиваем добровольное завершение рабочего потока.
         * workers[i] — дескриптор рабочего потока.
         * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
        if (!(fvm_worker_stop(workers[i]) == FVM_OK))
        /* Начинаем обработку неуспешного вызова или неверного результата. */
        {
            /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
            fvm_example_fail("fvm_worker_stop(workers[i]) == FVM_OK", __FILE__, __LINE__);
            /* Завершаем ветку ошибки. */
        }
        /* Завершаем текущий блок или описание объекта. */
    }
    /* Вызываем fvm_worker_join_all: ожидаем все переданные потоки и получаем их результаты.
     * workers — дескриптор рабочего потока.
     * 2 — число элементов.
     * outputs — значение или буфер значений.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_join_all(workers, 2, outputs) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_join_all(workers, 2, outputs) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Организуем повторение операций до выполнения условия завершения. */
    for (i = 0; i < 2; ++i)
    /* Начинаем блок инструкций или описание объекта. */
    {
        /* Проверяем результат предыдущей операции: outputs[i].type == FVM_VALUE_NUMBER &&
         * outputs[i].number == 42. Если условие ниже нарушено, печатаем место ошибки и завершаем
         * учебный процесс. */
        if (!(outputs[i].type == FVM_VALUE_NUMBER && outputs[i].number == 42))
        /* Начинаем обработку неуспешного вызова или неверного результата. */
        {
            /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
            fvm_example_fail("outputs[i].type == FVM_VALUE_NUMBER && outputs[i].number == 42",
                             /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                             __FILE__, __LINE__);
            /* Завершаем ветку ошибки. */
        }
        /* Освобождаем объект рабочего потока после завершения его работы. */
        fvm_worker_destroy(workers[i]);
        /* Завершаем текущий блок или описание объекта. */
    }
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return 0;
    /* Завершаем текущий блок или описание объекта. */
}
