#include "flashvm/worker.h"
/* Подключаем объявления используемых типов и функций. */
#include "../../example_support.h"
/* Compute and return callback. */
/* Определяем функцию callback; параметры передаются вызывающей стороной в указанном порядке. */
static FVM_Result callback(FVM_Context *ctx, const FVM_Value *in, FVM_Value *out, void *userdata)
/* Начинаем блок инструкций или описание объекта. */
{
    /* Завершаем выражение с указанным значением или аргументами. */
    (void)userdata;
    /* Проверяем условие перед выполнением следующей ветки. */
    if (!ctx || in->type != FVM_VALUE_NUMBER)
        /* Возвращаем результат вызывающей стороне и завершаем функцию. */
        return FVM_ERROR;
    /* Записываем числовое значение и соответствующий тег типа. */
    fvm_value_number(out, in->number + 1);
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return FVM_OK;
    /* Завершаем текущий блок или описание объекта. */
}

/* Initialize the example, run its API operations and release owned resources. */
/* Точка входа: запускаем последовательность действий этого примера. */
int main(void)
/* Начинаем блок инструкций или описание объекта. */
{

    /* Initialization / Инициализация локального состояния. */
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Config cfg;
    /* Сохраняем вычисленное значение: FVM_Worker *w. */
    FVM_Worker *w = 0;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_WorkerState state;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Value in, out;
    /* Вызываем fvm_config_init: заполняем настройки VM значениями по умолчанию.
     * &cfg — настройки VM.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_config_init(&cfg) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_config_init(&cfg) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Записываем числовое значение и соответствующий тег типа. */
    fvm_value_number(&in, 41);

    /* Computation / Вычисление и обновление состояния. */
    /* Вызываем fvm_worker_run_suspended: создаём поток, ожидающий явного запуска.
     * &cfg — настройки создаваемой VM.
     * callback — callback рабочего потока.
     * &in — начальное значение callback.
     * 0 — данные хоста, живущие до join.
     * &w — адрес для потока, который сначала ожидает start.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_run_suspended(&cfg, callback, &in, 0, &w) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_run_suspended(&cfg, callback, &in, 0, &w) == FVM_OK", __FILE__,
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_worker_state: читаем состояние рабочего потока.
     * w — дескриптор рабочего потока.
     * &state — дескриптор рабочего потока.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_state(w, &state) == FVM_OK && state == FVM_WORKER_SUSPENDED))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_state(w, &state) == FVM_OK && state == FVM_WORKER_SUSPENDED",
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_worker_start: разрешаем работу ранее приостановленного потока.
     * w — дескриптор рабочего потока.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_start(w) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_start(w) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_worker_join: ожидаем завершения потока и получаем его результат.
     * w — поток, завершения которого ожидаем.
     * &out — адрес для результата; строки живут до destroy потока.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_join(w, &out) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_join(w, &out) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Проверяем результат предыдущей операции: out.type == FVM_VALUE_NUMBER && out.number == 42.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(out.type == FVM_VALUE_NUMBER && out.number == 42))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("out.type == FVM_VALUE_NUMBER && out.number == 42", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_worker_state: читаем состояние рабочего потока.
     * w — дескриптор рабочего потока.
     * &state — дескриптор рабочего потока.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_state(w, &state) == FVM_OK && state == FVM_WORKER_JOINED))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_state(w, &state) == FVM_OK && state == FVM_WORKER_JOINED",
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Освобождаем объект рабочего потока после завершения его работы. */
    fvm_worker_destroy(w);
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return 0;
    /* Завершаем текущий блок или описание объекта. */
}
