/* Учебный пример: создаём векторный прямоугольник и заполняем его градиентом через C89 API. */
#include "flashvm/gradient.h" /* Подключаем типы контрольных точек, матрицы и функцию заливки. */
#include <stdio.h>            /* Подключаем диагностический вывод для результата и ошибок. */
#include <string.h>           /* Подключаем memset для начальной очистки команды и пикселей. */

/* Добавляем одну команду к пути; координаты копируются, память команды остаётся у вызывающего. */
static int add(FVM_Path *path, FVM_PathVerb verb, double x, double y)
{                                         /* Начинаем создание одной векторной команды. */
    FVM_PathCommand command;              /* Храним тип операции и до трёх пар координат. */
    memset(&command, 0, sizeof(command)); /* Обнуляем также неиспользуемые координаты команды. */
    command.verb = verb;                  /* Выбираем перемещение, линию или замыкание контура. */
    command.x[0] = x;                     /* Указываем горизонтальную координату в пикселях. */
    command.y[0] = y;                     /* Указываем вертикальную координату в пикселях. */
    return fvm_path_add(path, &command) ==
           FVM_OK; /* Копируем команду в принадлежащий path контур. */
} /* Завершаем добавление команды и сообщаем успех через 1. */

#include "stroke.inc" /* Подключаем C89 helper с тремя режимами градиентной обводки. */
#include "linear_rgb.inc" /* Подключаем сравнение RGB/linearRGB без нового ресурса или VM. */

/* Рисуем градиент и освобождаем путь; при NO_GRAPHICS объясняем выбор графической сборки. */
int main(void)
{                                      /* Начинаем работу самостоятельного примера C89. */
    FVM_Path *path = 0;                /* Будем владеть созданным путём до вызова fvm_path_destroy. */
    FVM_Gradient gradient;             /* Храним заимствованное описание заливки без собственного ресурса GC. */
    FVM_GradientStop stops[2];         /* Две контрольные точки существуют до завершения отрисовки. */
    FVM_RasterSurface surface;         /* Описываем принадлежащую программе RGBA-поверхность. */
    unsigned char pixels[32 * 32 * 4]; /* Выделяем 32 строки по 32 четырёхбайтовых пикселя. */
    FVM_Result result;                 /* Сохраняем код операции, чтобы обработать его явно. */
    memset(pixels, 0, sizeof(pixels)); /* Начинаем с полностью прозрачной поверхности. */
    surface.pixels = pixels;           /* Передаём заимствованный адрес массива, не меняя владение. */
    surface.width = 32;                /* Устанавливаем число пикселей по горизонтали. */
    surface.height = 32;               /* Устанавливаем число пикселей по вертикали. */
    surface.stride = 32 * 4;           /* Между началами строк расположены 128 байтов. */
    result = fvm_path_create(&path);   /* Создаём пустой редактируемый путь и получаем его адрес. */
    if (result != FVM_OK)              /* Прекращаем пример, если путь не удалось выделить. */
    {                                  /* Начинаем обработку ошибки создания пути. */
        fprintf(stderr, "path allocation failed: %d\n",
                (int)result); /* Печатаем конкретный код ошибки. */
        return 1;             /* Возвращаем оболочке признак неуспешного выполнения. */
    } /* Завершаем обработку ошибки выделения пути. */
    if (!add(path, FVM_PATH_MOVE, 4, 4) ||   /* Переносим начало контура в левый верхний угол. */
        !add(path, FVM_PATH_LINE, 28, 4) ||  /* Добавляем верхнюю сторону прямоугольника. */
        !add(path, FVM_PATH_LINE, 28, 28) || /* Добавляем правую сторону прямоугольника. */
        !add(path, FVM_PATH_LINE, 4, 28) ||  /* Добавляем нижнюю сторону прямоугольника. */
        !add(path, FVM_PATH_CLOSE, 0, 0))    /* Замыкаем левую сторону; CLOSE игнорирует координаты. */
    {                                        /* Начинаем очистку после неуспешного добавления геометрии. */
        fvm_path_destroy(path);              /* Освобождаем созданный путь и уже скопированные команды. */
        return 1;                            /* Не продолжаем отрисовку неполного прямоугольника. */
    } /* Завершаем обработку ошибки геометрии. */
    fvm_gradient_init(&gradient); /* Задаём линейную заливку и нейтральное преобразование цвета. */
    stops[0].ratio = 0;           /* Помещаем первый цвет в начало градиентной рампы. */
    stops[0].color.r = 255;       /* Первый цвет содержит максимальную красную компоненту. */
    stops[0].color.g = 0;         /* Первый цвет не содержит зелёной компоненты. */
    stops[0].color.b = 0;         /* Первый цвет не содержит синей компоненты. */
    stops[0].color.a = 255;       /* Первый цвет полностью непрозрачен. */
    stops[1].ratio = 1;           /* Помещаем второй цвет в конец градиентной рампы. */
    stops[1].color.r = 0;         /* Второй цвет не содержит красной компоненты. */
    stops[1].color.g = 0;         /* Второй цвет не содержит зелёной компоненты. */
    stops[1].color.b = 255;       /* Второй цвет содержит максимальную синюю компоненту. */
    stops[1].color.a = 255;       /* Второй цвет также полностью непрозрачен. */
    gradient.stops =
        stops;               /* Передаём заимствованный массив; функция отрисовки его не сохраняет. */
    gradient.count = 2;      /* Указываем точное число доступных контрольных точек. */
    gradient.matrix.xx = 16; /* Растягиваем нормализованный диапазон X от -1..1 до 32 пикселей. */
    gradient.matrix.yy = 16; /* Задаём такой же размер нормализованного диапазона Y. */
    gradient.matrix.x0 = 16; /* Переносим центр градиента в горизонтальную середину поверхности. */
    gradient.matrix.y0 = 16; /* Переносим центр градиента в вертикальную середину поверхности. */
    result = fvm_path_draw_gradient(path, &surface, &gradient,
                                    0); /* Рисуем заливку по правилу nonzero. */
    if (result == FVM_UNSUPPORTED)                                            /* Обрабатываем штатную сборку с отключённой графикой. */
    {                                                                         /* Начинаем пояснение графической конфигурации. */
        puts("Select GRAPHICS_AGG or GRAPHICS_CAIRO in DEFS.txt to render."); /* Называем доступные
                                                                                 backend. */
        fvm_path_destroy(path); /* Освобождаем путь также в сборке без графического backend. */
        return 0;                                                             /* Считаем отключённую графику корректным режимом этого учебного примера. */
    } /* Завершаем обработку NO_GRAPHICS. */
    if (result != FVM_OK) /* Проверяем все остальные ошибки матрицы, памяти и отрисовки. */
    {                     /* Начинаем выдачу ошибки отрисовки. */
        fprintf(stderr, "gradient drawing failed: %d\n",
                (int)result); /* Выводим возвращённый код. */
        fvm_path_destroy(path); /* Освобождаем путь после неуспешной заливки. */
        return 1;             /* Сообщаем оболочке о неуспешной отрисовке. */
    } /* Завершаем обработку ошибок отрисовки. */
    printf(
        "center RGBA: %u %u %u %u\n", /* Печатаем четыре прямые цветовые компоненты центра. */
        (unsigned int)
            pixels[(16 * 32 + 16) * 4],                /* Читаем красную компоненту центрального пикселя. */
        (unsigned int)pixels[(16 * 32 + 16) * 4 + 1],  /* Читаем зелёную компоненту. */
        (unsigned int)pixels[(16 * 32 + 16) * 4 + 2],  /* Читаем синюю компоненту. */
        (unsigned int)pixels[(16 * 32 + 16) * 4 + 3]); /* Читаем непрозрачность без premultiply. */
    result = gradient_stroke_demo(path, &surface, &gradient); /* Сравниваем pad, reflect и repeat на том же принадлежащем main пути. */
    if (result == FVM_OK) result = gradient_linear_rgb_demo(path, &surface); /* Проверяем цветовые политики после успешного spread-примера. */
    fvm_path_destroy(path); /* Освобождаем путь после всех синхронных заливок и обводок. */
    return result == FVM_OK ? 0 : 1; /* Возвращаем оболочке результат проверки примера. */
} /* Завершаем main; локальные массивы больше не используются. */
