#!/usr/bin/env python3
"""Deterministic linked startup SWF, child movie and form fixtures; no compiler dependency."""
from pathlib import Path
import struct


def rect(x0, x1, y0, y1):
    """Pack a bounded signed SWF RECT in MSB-first bit order."""
    values = (x0, x1, y0, y1)
    width = max(abs(value).bit_length() + 1 for value in values)
    bits = format(width, "05b") + "".join(
        format(value & ((1 << width) - 1), "0%db" % width) for value in values
    )
    bits += "0" * (-len(bits) % 8)
    return bytes(int(bits[i : i + 8], 2) for i in range(0, len(bits), 8))


def tag(code, body=b""):
    """Encode either SWF short or long tag length explicitly in little endian."""
    return (
        struct.pack("<H", code << 6 | len(body))
        if len(body) < 63
        else struct.pack("<HI", code << 6 | 63, len(body))
    ) + body


def push(*values):
    """Encode counted ActionPush fields without depending on any compiler."""
    data = b""
    for value in values:
        data += (
            b"\0" + value.encode() + b"\0"
            if isinstance(value, str)
            else b"\x07" + struct.pack("<i", value)
        )
    return b"\x96" + struct.pack("<H", len(data)) + data


def global_call(name, *args):
    """Push reversed AVM1 arguments and invoke a named global."""
    return push(*reversed(args), len(args), name) + b"\x3d\x17"


def method_call(owner, name, *args):
    """Resolve an owner and invoke a member with the original receiver."""
    return push(*reversed(args), len(args), owner) + b"\x1c" + push(name) + b"\x52\x17"


def swf(frames):
    """Wrap independent frame actions in a complete uncompressed SWF8."""
    body = rect(0, 640, 0, 640) + struct.pack("<HH", 24 * 256, len(frames))
    for actions in frames:
        body += tag(12, actions + b"\0") + tag(1)
    body += tag(0)
    return b"FWS\x08" + struct.pack("<I", len(body) + 8) + body


def require(path, expected):
    """Throw when a loaded value differs; this prevents a vacuous visual example."""
    failure = push("loaded value mismatch: " + path) + b"\x2a"
    return (
        push(path)
        + b"\x1c"
        + push(expected)
        + b"\x66\x9d\x02\0"
        + struct.pack("<h", len(failure))
        + failure
    )


def startup(prefix=""):
    """Create a child, queue data loads, then check them on later frames."""
    first = method_call("_root", "createEmptyMovieClip", "child", 1)
    first += global_call("loadMovie", prefix + "nested/child.swf", "child")
    first += method_call("_root", "loadVariables", prefix + "root-vars.txt")
    second = require("_root.greeting", "hello from root")
    third = require("_root.child.answer", "child origin works") + b"\x07"
    return swf([first, second, third])


def child_movie():
    """Load child-relative variables exactly once before stopping."""
    return swf([method_call("this", "loadVariables", "child-vars.txt") + b"\x07"])


def write():
    """Publish all fixture resources beside this generator, independent of process CWD."""
    folder = Path(__file__).resolve().parent
    data = startup()
    (folder / "start.swf").write_bytes(data)
    (folder / "nested").mkdir(exist_ok=True)
    (folder / "nested/child.swf").write_bytes(child_movie())
    (folder / "root-vars.txt").write_bytes(b"greeting=hello+from+root")
    (folder / "nested/child-vars.txt").write_bytes(b"answer=child%20origin%20works")
    lines = [
        "/* Linked startup SWF generated by make_movies.py; see README.md. */",
        "#ifndef EXAMPLE_LOADING_STARTUP_H /* Guard the immutable resource. */",
        "#define EXAMPLE_LOADING_STARTUP_H /* Binary data is not a terminated string. */",
        "static const unsigned char loading_startup[] = { /* Exact SWF8 bytes. */",
    ]
    for offset in range(0, len(data), 12):
        lines.append(
            "    "
            + ", ".join("0x%02x" % value for value in data[offset : offset + 12])
            + ", /* Wire bytes %d..%d. */" % (offset, min(offset + 11, len(data) - 1))
        )
    lines += [
        "}; /* sizeof reports the complete binary resource. */",
        "#endif /* End private linked startup resource. */",
    ]
    (folder / "startup.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    write()
