#!/usr/bin/env python3
"""Regenerate C++98 case data from the bundled Unicode 3.2 input files."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
base = root / "external/unicode"
records = {}
for line in (base / "UnicodeData-3.2.0.txt").read_text().splitlines():
    fields = line.split(";")
    cp = int(fields[0], 16)
    upper = [int(fields[12], 16)] if fields[12] else [cp]
    lower = [int(fields[13], 16)] if fields[13] else [cp]
    records[cp] = [lower, upper, fields[2]]
for line in (base / "SpecialCasing-3.2.0.txt").read_text().splitlines():
    fields = line.split("#")[0].strip().split(";")
    if len(fields) < 4 or (len(fields) > 4 and fields[4].strip()):
        continue
    cp = int(fields[0].strip(), 16)
    records[cp][0] = [int(x, 16) for x in fields[1].split()]
    records[cp][1] = [int(x, 16) for x in fields[3].split()]


def ranges(values):
    result = []
    for cp in sorted(values):
        if result and cp == result[-1][1] + 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


out = [
    "/* Generated by scripts/generate_unicode_case.py; Unicode 3.2.0.",
    " * Unicode data copyright/license: external/unicode/LICENSE.txt. */",
    "#ifndef FVM_UNICODE_CASE_TABLE_HPP",
    "#define FVM_UNICODE_CASE_TABLE_HPP",
    "struct FVM_CaseMapping { unsigned long cp, lower[3], upper[3]; unsigned int nl, nu; };",
    "static const FVM_CaseMapping fvm_case_mappings[] = {",
]
for cp, (lower, upper, category) in sorted(records.items()):
    if lower == [cp] and upper == [cp]:
        continue
    if not (len(lower) <= 3 and len(upper) <= 3):
        raise AssertionError("condition check failed: flashVM/scripts/generate_unicode_case.py:44")

    def row(seq):
        return ", ".join("0x%xUL" % x for x in seq + [0] * (3 - len(seq)))

    out.append(
        "    {0x%xUL, {%s}, {%s}, %d, %d}," % (cp, row(lower), row(upper), len(lower), len(upper))
    )
out.append("};")
out.append("struct FVM_CaseRange { unsigned long first, last; };")
for name, predicate in [
    ("cased", lambda cp, r: r[2] in ["Lu", "Ll", "Lt"]),
    ("ignored", lambda cp, r: r[2] in ["Mn", "Me", "Cf", "Lm", "Sk"] or cp in [0x27, 0x2019]),
]:
    out.append("static const FVM_CaseRange fvm_case_%s[] = {" % name)
    for first, last in ranges(cp for cp, r in records.items() if predicate(cp, r)):
        out.append("    {0x%xUL, 0x%xUL}," % (first, last))
    out.append("};")
out.append("#endif")
(base / "case_table.hpp").write_text("\n".join(out) + "\n")
