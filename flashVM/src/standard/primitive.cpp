/* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
FVM_Result fvm_to_primitive(FVM_Context *c,
                            const FVM_Value *input,
                            bool string_hint,
                            /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                            FVM_Value *out)
/* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
{ /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
    if (!c || !input || !out || fvm_validate_value(c, input) != FVM_OK)
    { /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_INVALID_ARGUMENT;
    }
    /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
    if (input->type != FVM_VALUE_OBJECT)
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        *out = *input;
        /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_OK;
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    }
    /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
    if (c->primitive_depth >= 64)
    { /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_UNSUPPORTED;
    }
    /* [GC:] Сохраняем корректное состояние сборщика при исключениях. */
    try
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        fvm_detail::vector<FVM_Value> values;
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        values.push_back(*input);
        /* [GC:] Описываем или используем состояние сборщика и его активные корни. */
        FVM_GCRootFrame frame;
        /* [GC:] Сохраняем предыдущий корень для восстановления цепочки после выхода. */
        frame.previous = c->gc_frames;
        /* [GC:] Подключаем стек, локальные значения или получателя к активному корню вызова. */
        frame.stack = &values;
        /* [GC:] Подключаем стек, локальные значения или получателя к активному корню вызова. */
        frame.locals = 0;
        /* [GC:] Подключаем стек, локальные значения или получателя к активному корню вызова. */
        frame.receiver = input->object;
        /* [GC:] Обновляем цепочку активных корней; порядок восстановления должен быть LIFO. */
        c->gc_frames = &frame;
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        ++c->primitive_depth;
        /* Define Pop struct and its representation. */
        /* [GC:] Объявляем представление состояния сборщика или корней. */
        struct Pop
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
        { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
            FVM_Context *c;
            /* [GC:] Описываем или используем состояние сборщика и его активные корни. */
            FVM_GCRootFrame *previous;
            /* Release the resources owned by this Pop instance. */
            /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
            ~Pop()
            /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
            {

                /* Computation / Вычисление и обновление состояния. */
                /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                --c->primitive_depth;
                /* [GC:] Обновляем цепочку активных корней; порядок восстановления должен быть LIFO.
                 */
                /* [GC:] Обновляем цепочку активных корней; порядок восстановления должен быть LIFO.
                 */
                c->gc_frames = previous;
                /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
            }
            /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        } pop;
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        pop.c = c;
        /* [GC:] Сохраняем предыдущий корень для восстановления цепочки после выхода. */
        pop.previous = frame.previous;
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        const char *names[2] = {string_hint ? "toString" : "valueOf",
                                /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                                string_hint ? "valueOf" : "toString"};
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        bool callable = false;
        /* [GC:] Обходим корни, ссылки или записи кучи в этой фазе сборки. */
        for (unsigned int i = 0; i < 2; ++i)
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
        { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
            FVM_Value method;
            /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
            FVM_Result r = fvm_object_get(c, input->object, names[i], &method);
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            if (r != FVM_OK)
            { /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
                return r;
            }
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            if (method.type != FVM_VALUE_OBJECT)
            { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                continue;
            }
            /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
            FVM_Value result;
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            if (method.object->invocable.callback)
            { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                r = fvm_function_invoke(c, method.object, input->object, 0, 0, &result);
            }
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            else if (method.object->callable.callback)
            { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                r = fvm_callable_invoke(c, method.object, 0, 0, &result);
            }
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            else
            { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                continue;
            }
            /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
            callable = true;
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            if (r != FVM_OK)
            { /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
                return r;
            }
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            if (fvm_validate_value(c, &result) != FVM_OK)
            { /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
                return FVM_INVALID_ARGUMENT;
            }
            /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
            if (result.type != FVM_VALUE_OBJECT)
            /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
            { /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
                *out = result;
                /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
                return FVM_OK;
                /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
            }
            /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
        }
        /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
        if (!callable && string_hint)
        { /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
            return fvm_value_string(out, "[object Object]");
        }
        /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_UNSUPPORTED;
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    }
    /* [GC:] Сохраняем корректное состояние сборщика при исключениях. */
    catch (const std::bad_alloc &)
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    { /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_OUT_OF_MEMORY;
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    }
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
}
