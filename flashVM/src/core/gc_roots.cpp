/* [GC:] Define FVM_GCRootScope struct and its representation. */
/* [GC:] Объявляем представление состояния сборщика или корней. */
struct FVM_GCRootScope
/* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
{
    /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
    FVM_Context *context;
    /* [GC:] Описываем или используем состояние сборщика и его активные корни. */
    FVM_GCRootFrame frame;
    /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
    fvm_detail::vector<FVM_Value> values;
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
};
/* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
extern "C"
/* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
{
    /* Push a temporary root frame onto this context and return its scope handle. */
    /* [GC:] Открываем область временных корней для защищаемых значений. */
    FVM_Result fvm_gc_roots_begin(FVM_Context *context, FVM_GCRootScope **out)
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    {
        /* [GC:] Учитываем флаг активной сборки и предотвращаем повторный вход. */
        if (!context || !out || context->gc_collecting)
            /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
            return FVM_INVALID_ARGUMENT;
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        *out = 0;
        /* [GC:] Описываем или используем состояние сборщика и его активные корни. */
        FVM_GCRootScope *scope = new (std::nothrow) FVM_GCRootScope;
        /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
        if (!scope)
            /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
            return FVM_OUT_OF_MEMORY;

        /* Computation / Вычисление и обновление состояния. */
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        scope->context = context;
        /* [GC:] Сохраняем предыдущий корень для восстановления цепочки после выхода. */
        scope->frame.previous = context->gc_frames;
        /* [GC:] Подключаем стек, локальные значения или получателя к активному корню вызова. */
        scope->frame.stack = &scope->values;
        /* [GC:] Подключаем стек, локальные значения или получателя к активному корню вызова. */
        scope->frame.locals = 0;
        /* [GC:] Подключаем стек, локальные значения или получателя к активному корню вызова. */
        scope->frame.receiver = 0;
        /* [GC:] Обновляем цепочку активных корней; порядок восстановления должен быть LIFO. */
        context->gc_frames = &scope->frame;
        /* [GC:] Операция в блоке управления достижимостью и временем жизни объектов. */
        *out = scope;
        /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_OK;
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    }
    /* Copy a validated value into the active temporary root scope. */
    /* [GC:] Регистрируем значение в области временных корней. */
    FVM_Result fvm_gc_roots_add(FVM_GCRootScope *scope, const FVM_Value *value)
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    {
        /* [GC:] Учитываем флаг активной сборки и предотвращаем повторный вход. */
        if (!scope || !value || scope->context->gc_collecting)
            /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
            return FVM_INVALID_ARGUMENT;
        /* [GC:] Выбираем безопасную ветку обработки состояния сборки или корней. */
        if (fvm_validate_value(scope->context, value) != FVM_OK)
            /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
            return FVM_INVALID_ARGUMENT;
        /* [GC:] Сохраняем корректное состояние сборщика при исключениях. */
        try
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
        {
            /* [GC:] Сохраняем копию защищаемого значения в трассируемой области корней. */
            scope->values.push_back(*value);
            /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
        }
        /* [GC:] Сохраняем корректное состояние сборщика при исключениях. */
        catch (...)
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
        {
            /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
            return FVM_OUT_OF_MEMORY;
            /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
        }
        /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_OK;
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    }
    /* Pop the most recent temporary root frame and release its scope handle. */
    /* [GC:] Закрываем область временных корней в обратном порядке открытия. */
    FVM_Result fvm_gc_roots_end(FVM_GCRootScope *scope)
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    {
        /* [GC:] Учитываем флаг активной сборки и предотвращаем повторный вход. */
        if (!scope || scope->context->gc_frames != &scope->frame || scope->context->gc_collecting)
            /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
            return FVM_INVALID_ARGUMENT;
        /* [GC:] Обновляем цепочку активных корней; порядок восстановления должен быть LIFO. */
        scope->context->gc_frames = scope->frame.previous;
        /* [GC:] Удаляем запись или область корней после завершения работы с ней. */
        delete scope;
        /* [GC:] Возвращаем результат операции сборщика или защиты корней. */
        return FVM_OK;
        /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
    }
    /* [GC:] Граница блока, управляющего жизненным циклом объектов или корней. */
}
