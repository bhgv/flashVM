#!/usr/bin/env python3
"""Embed readable AS adapter templates for the dependency-free C99 generator.

The checked-in header lets normal native builds run without Python. Edit the AS
sources, regenerate explicitly, then use --check to detect an outdated header.
"""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]  # Workspace owning the readable templates.
SOURCE = ROOT / "compiler/limbo/frontend/as-runtime"  # Authoritative AS template directory.
OUTPUT = SOURCE.parent / "bindings_as_runtime.h"  # Checked-in C99 embedding consumed by bindings.c.


# Serialize unchanged AS bytes as an array of C string lines, preserving line boundaries.
# Parameters: none. Returns the complete generated header text; writes no files.
def render():
    """Keep encoding and names deterministic across regeneration hosts."""
    blocks = ["/* Generated by tools/embed_as_runtime.py; edit the AS templates in as-runtime. */\n"]
    for name in ("guards", "module", "proxy"):
        source = (SOURCE / (name + ".as.in")).read_text()
        declaration = "static const char *const as_" + name + "_template[] = {\n"
        literals = "\n".join("    " + json.dumps(line) + "," for line in source.splitlines(True))
        blocks.append(declaration + literals + "\n    NULL\n};\n")
    return "\n\n".join(blocks)


# Regenerate explicitly or compare the checked-in embedding without editing it.
# Parameters: CLI --check selects read-only validation. Returns zero on agreement.
def main():
    """Fail on stale generated text instead of silently compiling another template."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if OUTPUT.read_text() != expected:
            print("Outdated AS embedding: run python3 tools/embed_as_runtime.py")
            return 1
        return 0
    OUTPUT.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
