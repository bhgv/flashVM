#!/usr/bin/env python3
"""Regenerate locale-independent Unicode 3.2 category ranges for detached AS parsers.

Python exposes this immutable historic database as unicodedata.ucd_3_2_0.
Builds use checked-in C99 data and do not require Python or a Unicode library.
"""
import argparse
import re
from atg_format import tokens
from pathlib import Path
import unicodedata


def ranges(categories):
    """Coalesce adjacent Unicode scalars with a selected General_Category."""
    result = []
    for code in range(0x110000):
        if unicodedata.ucd_3_2_0.category(chr(code)) in categories:
            if result and result[-1][1] + 1 == code:
                result[-1][1] = code
            else:
                result.append([code, code])
    return result


def render():
    """Emit portable unsigned-long endpoints, without host wchar_t assumptions."""
    text = [
        "/* Generated by tools/generate_parser_unicode.py; Unicode 3.2.0.",
        " * General_Category source: Python unicodedata.ucd_3_2_0.",
        " * Start: Lu Ll Lt Lm Lo Nl; additional part: Mn Mc Nd Pc.",
        " * ASCII $, _, and ZWNJ/ZWJ are handled explicitly in the ATG.",
        " * Data provenance: https://www.unicode.org/versions/Unicode3.2.0/ */",
        "typedef struct",
        "{",
        "    unsigned long first; /* Inclusive first scalar. */",
        "    unsigned long last; /* Inclusive last scalar. */",
        "} IdentifierRange;",
    ]
    for name, categories in [
        ("identifier_start_ranges", {"Lu", "Ll", "Lt", "Lm", "Lo", "Nl"}),
        ("identifier_part_ranges", {"Mn", "Mc", "Nd", "Pc"}),
    ]:
        text.append("static const IdentifierRange " + name + "[] = {")
        text += ["    {0x%xUL, 0x%xUL}," % tuple(pair) for pair in ranges(categories)]
        text.append("};")
    return "\n".join(text) + "\n"


def main():
    """Write or compare each independently buildable language's identical table."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    expected = render()
    bad = []
    for language in ("as1", "as2", "as3"):
        path = root / "compiler" / language / "frontend" / "unicode_ident.inc"
        grammar = path.with_name(language + ".atg")
        source = grammar.read_text()
        keywords = sorted(
            {
                value[1:-1]
                for kind, value in tokens(source[source.index("PRODUCTIONS") :])
                if kind == "token" and re.fullmatch(r'"[A-Za-z_][A-Za-z_0-9]*"', value)
            }
        )
        match = re.search(r"(static const char \*const reserved\[\] = \{)(.*?)(\};)", source, re.S)
        actual = re.findall(r'"([^"]*)"', match[2]) if match else []
        if actual != keywords:
            if args.check or not match:
                bad.append(str(grammar) + " reserved keyword table")
            else:
                source = (
                    source[: match.start(2)]
                    + ", ".join('"' + word + '"' for word in keywords)
                    + source[match.end(2) :]
                )
                grammar.write_text(source)
        if args.check:
            if not path.exists() or path.read_text() != expected:
                bad.append(str(path))
        else:
            path.write_text(expected)
    if bad:
        parser.error("stale Unicode tables: " + ", ".join(bad))
    print("Unicode 3.2 tables: " + ("checked" if args.check else "generated"))


if __name__ == "__main__":
    main()
