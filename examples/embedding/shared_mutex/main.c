/* C89: transfer a shared mutex to a worker through a channel of VM values. */
/* Подключаем объявления используемых типов и функций. */
#include "flashvm/extensions.h"
/* Подключаем объявления используемых типов и функций. */
#include "flashvm/mutex.h"
/* Подключаем объявления используемых типов и функций. */
#include "flashvm/transfer.h"
/* Подключаем объявления используемых типов и функций. */
#include "flashvm/worker.h"
/* Подключаем объявления используемых типов и функций. */
#include <assert.h>
/* Подключаем объявления используемых типов и функций. */
#include <stdio.h>
/* Compute and return worker. */
/* Выполняем вызов worker с указанными аргументами. */
static FVM_Result worker(FVM_Context *c, const FVM_Value *in, FVM_Value *out, void *user)
/* Начинаем блок инструкций или описание объекта. */
{

    /* Initialization / Инициализация локального состояния. */
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Value lock, result;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Result r;

    /* Computation / Вычисление и обновление состояния. */
    /* Завершаем выражение с указанным значением или аргументами. */
    (void)in;
    /* Восстанавливаем полученный граф значения в контексте получателя. */
    r = fvm_channel_receive_value(c, (FVM_Channel *)user, &lock, 1);
    /* Проверяем условие перед выполнением следующей ветки. */
    if (r != FVM_OK)
        /* Возвращаем результат вызывающей стороне и завершаем функцию. */
        return r;
    /* Выполняем вызов fvm_object_call с указанными аргументами. */
    r = fvm_object_call(c, lock.object, "set", 0, 0, &result);
    /* Проверяем условие перед выполнением следующей ветки. */
    if (r != FVM_OK)
        /* Возвращаем результат вызывающей стороне и завершаем функцию. */
        return r;
    /* Shared protected application work belongs here. */
    /* Выполняем вызов fvm_object_call с указанными аргументами. */
    r = fvm_object_call(c, lock.object, "reset", 0, 0, &result);
    /* Записываем логическое значение и соответствующий тег типа. */
    fvm_value_boolean(out, r == FVM_OK);
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return r;
    /* Завершаем текущий блок или описание объекта. */
}

/* Initialize the example, run its API operations and release owned resources. */
/* Точка входа: запускаем последовательность действий этого примера. */
int main(void)
/* Начинаем блок инструкций или описание объекта. */
{

    /* Initialization / Инициализация локального состояния. */
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Config cfg;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Runtime *rt;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Context *c;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Channel *pipe;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Worker *task;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Value mutex, lock, input, result;
    /* Инициализируем настройки безопасными значениями по умолчанию. Проверяем успешность вызова. */
    assert(fvm_config_init(&cfg) == FVM_OK);
    /* Создаём среду выполнения; её необходимо освободить после контекстов. Проверяем успешность
     * вызова. */
    assert(fvm_runtime_create(&cfg, &rt) == FVM_OK);
    /* Создаём отдельный контекст интерпретатора в среде выполнения. Проверяем успешность вызова. */
    assert(fvm_context_create(rt, &c) == FVM_OK);

    /* Computation / Вычисление и обновление состояния. */
    /* Выполняем вызов assert с указанными аргументами. */
    assert(fvm_extensions_install(c) == FVM_OK);
    /* Читаем значение из глобальной области контекста. Проверяем успешность вызова. */
    assert(fvm_get_global(c, "mutex", &mutex) == FVM_OK);
    /* Выполняем вызов assert с указанными аргументами. */
    assert(fvm_object_call(c, mutex.object, "new", 0, 0, &lock) == FVM_OK);
    /* Создаём канал для обмена сообщениями внутри процесса. Проверяем успешность вызова. */
    assert(fvm_channel_create(&pipe) == FVM_OK);

    /* Output / Вывод и передача результата. */
    /* Передаём граф значения через канал с учётом режима ожидания. Проверяем успешность вызова. */
    assert(fvm_channel_send_value(c, pipe, &lock, 0) == FVM_OK);
    /* Сбрасываем все поля значения в состояние undefined. */
    fvm_value_undefined(&input);

    /* Computation / Вычисление и обновление состояния. */
    /* Выполняем вызов assert с указанными аргументами. */
    assert(fvm_worker_run(&cfg, worker, &input, pipe, &task) == FVM_OK);
    /* Ожидаем завершения рабочего потока. Проверяем успешность вызова. */
    assert(fvm_worker_join(task, &result) == FVM_OK && result.boolean);

    /* Output / Вывод и передача результата. */
    /* Выводим результат в стандартный поток вывода. */
    printf("Shared mutex acquired and released by the worker.\n");

    /* Cleanup / Освобождение ресурсов. */
    /* Освобождаем объект рабочего потока после завершения его работы. */
    fvm_worker_destroy(task);
    /* Освобождаем принадлежащую примеру ссылку на канал. */
    fvm_channel_destroy(pipe);
    /* Освобождаем контекст и принадлежащие ему объекты. */
    fvm_context_destroy(c);
    /* Освобождаем среду выполнения после завершения работы контекстов. */
    fvm_runtime_destroy(rt);
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return 0;
    /* Завершаем текущий блок или описание объекта. */
}
