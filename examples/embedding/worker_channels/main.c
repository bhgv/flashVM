/* Define Exchange struct and its representation. */
/* Объявляем тип, используемый в этом примере. */
typedef struct Exchange
/* Начинаем блок инструкций или описание объекта. */
{
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Channel *requests;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Channel *replies;
    /* Завершаем выражение с указанным значением или аргументами. */
} Exchange;

/* The callback runs in its own VM. The channels, not Flash objects,
 * are the only shared data between this context and the host. */
/* Compute and return exchange worker. */
/* Определяем функцию exchange_worker; параметры передаются вызывающей стороной в указанном порядке. */
static FVM_Result
/* Продолжаем объявление функции обмена в рабочем потоке. */
exchange_worker(FVM_Context *ctx, const FVM_Value *input, FVM_Value *output,
                /* Продолжаем объявление или выражение с указанными параметрами. */
                void *userdata)
/* Начинаем блок инструкций или описание объекта. */
{

    /* Initialization / Инициализация локального состояния. */
    /* Сохраняем вычисленное значение: Exchange *ex. */
    Exchange *ex = (Exchange *)userdata;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Value request, reply;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Result r;

    /* Computation / Вычисление и обновление состояния. */
    /* Завершаем выражение с указанным значением или аргументами. */
    (void)ctx;
    /* Завершаем выражение с указанным значением или аргументами. */
    (void)input;
    /* Получаем значение; вызов ожидает сообщение или закрытие канала. */
    r = fvm_channel_receive(ex->requests, &request);
    /* Проверяем условие перед выполнением следующей ветки. */
    if (r != FVM_OK)
        /* Возвращаем результат вызывающей стороне и завершаем функцию. */
        return r;
    /* Проверяем условие перед выполнением следующей ветки. */
    if (request.type != FVM_VALUE_STRING)
        /* Возвращаем результат вызывающей стороне и завершаем функцию. */
        return FVM_INVALID_ARGUMENT;
    /* Записываем числовое значение и соответствующий тег типа. */
    fvm_value_number(&reply, (double)strlen(request.string));

    /* Output / Вывод и передача результата. */
    /* Отправляем значение; вызов может ожидать освобождения очереди. */
    r = fvm_channel_send(ex->replies, &reply);
    /* Проверяем условие перед выполнением следующей ветки. */
    if (r == FVM_OK)
        /* Записываем числовое значение и соответствующий тег типа. */
        fvm_value_number(output, 42.0);
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return r;
    /* Завершаем текущий блок или описание объекта. */
}

/* Initialize the example, run its API operations and release owned resources. */
/* Точка входа: запускаем последовательность действий этого примера. */
int main(void)
/* Начинаем блок инструкций или описание объекта. */
{

    /* Initialization / Инициализация локального состояния. */
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Config cfg;
    /* Сохраняем вычисленное значение: FVM_Worker *worker. */
    FVM_Worker *worker = 0;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    FVM_Value input, message, reply, output;
    /* Завершаем выражение с указанным значением или аргументами. */
    Exchange ex;
    /* Объявляем данные или дескрипторы, используемые в следующем блоке. */
    int available;
    /* Вызываем fvm_config_init: заполняем настройки VM значениями по умолчанию.
     * &cfg — настройки VM.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_config_init(&cfg) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_config_init(&cfg) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_channel_create: создаём внутрипроцессный канал сообщений.
     * &ex.requests — адрес или буфер для результата.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_channel_create(&ex.requests) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_channel_create(&ex.requests) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_channel_create: создаём внутрипроцессный канал сообщений.
     * &ex.replies — адрес или буфер для результата.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_channel_create(&ex.replies) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_channel_create(&ex.replies) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_channel_try_receive: пытаемся прочитать сообщение без ожидания.
     * ex.replies — контекст интерпретатора.
     * &reply — адрес или буфер для результата.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_channel_try_receive(ex.replies, &reply) == FVM_NOT_FOUND))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_channel_try_receive(ex.replies, &reply) == FVM_NOT_FOUND", __FILE__,
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Сбрасываем все поля значения в состояние undefined. */
    fvm_value_undefined(&input);
    /* Вызываем fvm_worker_run_suspended: создаём поток, ожидающий явного запуска.
     * &cfg — настройки создаваемой VM.
     * exchange_worker — callback рабочего потока.
     * &input — начальное значение callback.
     * &ex — данные хоста, живущие до join.
     * &worker — адрес для потока, который сначала ожидает start.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_run_suspended(&cfg, exchange_worker, &input, &ex, &worker) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail(
            /* Продолжаем условие проверки или аргументы диагностического сообщения. */
            "fvm_worker_run_suspended(&cfg, exchange_worker, &input, &ex, &worker) == FVM_OK",
            /* Передаём имя исходного файла и номер строки неуспешной проверки. */
            __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_value_string: создаём строковое значение по правилам владения API.
     * &message — передаваемое значение.
     * "hello" — строка или используемый дескриптор.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_value_string(&message, "hello") == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_value_string(&message, \"hello\") == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }

    /* Output / Вывод и передача результата. */
    /* Вызываем fvm_channel_send: отправляем значение в очередь; вызов может ожидать.
     * ex.requests — канал назначения.
     * &message — значение для копирования в очередь.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_channel_send(ex.requests, &message) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_channel_send(ex.requests, &message) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }

    /* Computation / Вычисление и обновление состояния. */
    /* Вызываем fvm_worker_start: разрешаем работу ранее приостановленного потока.
     * worker — дескриптор рабочего потока.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_start(worker) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_start(worker) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_channel_receive: ожидаем сообщение и получаем значение из очереди.
     * ex.replies — канал-источник.
     * &reply — адрес для сообщения; полученная строка временно принадлежит каналу.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_channel_receive(ex.replies, &reply) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_channel_receive(ex.replies, &reply) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Проверяем результат предыдущей операции: reply.type == FVM_VALUE_NUMBER && reply.number
     * == 5.0. Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(reply.type == FVM_VALUE_NUMBER && reply.number == 5.0))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("reply.type == FVM_VALUE_NUMBER && reply.number == 5.0", __FILE__,
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_worker_join: ожидаем завершения потока и получаем его результат.
     * worker — поток, завершения которого ожидаем.
     * &output — адрес для результата; строки живут до destroy потока.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_worker_join(worker, &output) == FVM_OK))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_worker_join(worker, &output) == FVM_OK", __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Проверяем результат предыдущей операции: output.type == FVM_VALUE_NUMBER && output.number
     * == 42.0. Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(output.type == FVM_VALUE_NUMBER && output.number == 42.0))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("output.type == FVM_VALUE_NUMBER && output.number == 42.0", __FILE__,
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Освобождаем объект рабочего потока после завершения его работы. */
    fvm_worker_destroy(worker);

    /* Computation / Вычисление и обновление состояния. */
    /* Закрываем канал и пробуждаем ожидающих участников. */
    fvm_channel_close(ex.requests);
    /* Вызываем fvm_channel_try_receive: пытаемся прочитать сообщение без ожидания.
     * ex.requests — контекст интерпретатора.
     * &reply — адрес или буфер для результата.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_channel_try_receive(ex.requests, &reply) == FVM_ERROR))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_channel_try_receive(ex.requests, &reply) == FVM_ERROR", __FILE__,
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __LINE__);
        /* Завершаем ветку ошибки. */
    }
    /* Вызываем fvm_channel_available: проверяем наличие сообщения без извлечения.
     * ex.requests — контекст интерпретатора.
     * &available — адрес для признака наличия сообщения в очереди.
     * Если условие ниже нарушено, печатаем место ошибки и завершаем учебный процесс. */
    if (!(fvm_channel_available(ex.requests, &available) == FVM_OK && !available))
    /* Начинаем обработку неуспешного вызова или неверного результата. */
    {
        /* Выводим исходное условие, имя файла и номер строки; этот вызов не возвращается. */
        fvm_example_fail("fvm_channel_available(ex.requests, &available) == FVM_OK && !available",
                         /* Передаём имя исходного файла и номер строки неуспешной проверки. */
                         __FILE__, __LINE__);
        /* Завершаем ветку ошибки. */
    }

    /* Cleanup / Освобождение ресурсов. */
    /* Освобождаем принадлежащую примеру ссылку на канал. */
    fvm_channel_destroy(ex.requests);
    /* Освобождаем принадлежащую примеру ссылку на канал. */
    fvm_channel_destroy(ex.replies);
    /* Возвращаем результат вызывающей стороне и завершаем функцию. */
    return 0;
    /* Завершаем текущий блок или описание объекта. */
}
